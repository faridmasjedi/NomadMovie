// Writes THIRD_PARTY_NOTICES.md: everything NomadMovie ships that it didn't write, with the license texts.
//   npm run licenses
// • the packages compiled into the editor (asks Vite which modules end up in the bundle)
// • the packages the desktop app's engine loads at run time (npm's production dependency tree)
// • ffmpeg (GPL), the bundled fonts, and the AI model downloaded on first use
import { build } from "vite";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const own = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")).name;

/** node_modules/<pkg> folder that contains a file */
const pkgDir = (file) => {
  const m = /^(.*node_modules[\\/](?:@[^\\/]+[\\/])?[^\\/]+)/.exec(file);
  return m ? m[1] : null;
};

const dirs = new Set();

// 1. the editor: every module Vite puts in the production bundle
await build({
  root,
  logLevel: "silent",
  build: { write: false },
  plugins: [
    {
      name: "collect-packages",
      generateBundle() {
        for (const id of this.getModuleIds()) {
          const d = pkgDir(id.split("?")[0].replace(/^\0/, ""));
          if (d) dirs.add(d);
        }
      },
    },
  ],
});

// 2. the desktop app's engine: production dependencies, installed next to the app
// (--long marks leftovers nothing depends on as EXTRANEOUS: they aren't part of the app)
// (lines are "<path>:<name>@<version>:…"; on Windows the path itself starts with "D:")
const win = process.platform === "win32";
const prod = execFileSync(win ? "npm.cmd" : "npm", ["ls", "--omit=dev", "--all", "--parseable", "--long"], { cwd: root, encoding: "utf8", shell: win })
  .split(/\r?\n/)
  .filter((l) => l.trim() && !/:EXTRANEOUS|:INVALID/.test(l))
  .map((l) => l.split(/:(?![\\/])/)[0].trim())
  .filter((l) => l && l !== root);
for (const d of prod) dirs.add(d);

/** "github:owner/repo", "owner/repo", "git+ssh://git@github.com/…" → https://github.com/… */
const repoUrl = (r) => {
  r = r.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^(ssh:\/\/)?git@github\.com[:/]/, "https://github.com/").replace(/^git:\/\//, "https://");
  if (/^github:/.test(r)) return `https://github.com/${r.slice(7)}`;
  if (/^[\w.-]+\/[\w.-]+$/.test(r)) return `https://github.com/${r}`;
  return r;
};

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.(md|txt|markdown))?$/i;
const packages = [...dirs]
  .map((dir) => {
    let pj;
    try {
      pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    } catch {
      return null;
    }
    if (!pj.name || pj.name === own) return null;
    const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
    const text = files.map((f) => fs.readFileSync(path.join(dir, f), "utf8").trim()).join("\n\n");
    const license = typeof pj.license === "string" ? pj.license : pj.license?.type ?? (pj.licenses ?? []).map((l) => l.type).join(" OR ") ?? "";
    const repo = typeof pj.repository === "string" ? pj.repository : pj.repository?.url ?? "";
    return { name: pj.name, version: pj.version, license: license || "see text", repo: repoUrl(repo), text };
  })
  .filter(Boolean);

// one entry per name@version
const unique = [...new Map(packages.map((p) => [`${p.name}@${p.version}`, p])).values()].sort((a, b) => a.name.localeCompare(b.name));

const ffmpeg = JSON.parse(fs.readFileSync(path.join(root, "node_modules/ffmpeg-static/package.json"), "utf8"));
const ffmpegTag = ffmpeg["ffmpeg-static"]?.["binary-release-tag"] ?? "";
const ffmpegLicense = fs.readFileSync(path.join(root, "node_modules/ffmpeg-static/ffmpeg.LICENSE"), "utf8").trim();

